import { IndicatorScoreEntry, SupervisionInstrument } from '../types/sims';

export interface SupervisionCalculationResult {
  totalScore: number;
  maxScore: number;
  finalScore: number;
  predicate: string;
  unfilledCount: number;
  duplicateCount: number;
  eligibleForGtkRoom: boolean;
}

export function getSupervisionPredicate(nilai: number): string {
  if (nilai >= 91) return 'Sangat Baik';
  if (nilai >= 76) return 'Baik';
  if (nilai >= 61) return 'Cukup (Butuh Perbaikan)';
  if (nilai >= 51) return 'Kurang';
  return 'Sangat Kurang';
}

export function calculateSupervisionMetrics(
  instrument: SupervisionInstrument,
  scoresMap: Record<string, IndicatorScoreEntry>
): SupervisionCalculationResult {
  const totalItems = instrument.indicators.length;
  const maxScore = totalItems * 4;
  let totalScore = 0;
  let unfilledCount = 0;

  for (const ind of instrument.indicators) {
    const entry = scoresMap[ind.id];
    if (!entry || entry.scale === null || entry.scale === undefined) {
      unfilledCount += 1;
    } else {
      totalScore += entry.scale;
    }
  }

  const finalScore = maxScore > 0 ? Number(((totalScore / maxScore) * 100).toFixed(2)) : 0;
  const predicate = getSupervisionPredicate(finalScore);

  return {
    totalScore,
    maxScore,
    finalScore,
    predicate,
    unfilledCount,
    duplicateCount: 0, // Dijamin 0 secara struktural melalui kontrol skala eksklusif 1-4
    eligibleForGtkRoom: finalScore >= 76,
  };
}

